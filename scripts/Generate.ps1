function TypeName([type]$t){
    if($t.IsGenericType){return ($t.GetGenericTypeDefinition().FullName.Split('`')[0]+'['+(($t.GenericTypeArguments|ForEach-Object {TypeName $_}) -join ',')+']')}
    return $t.FullName
}
$verbs=@{Get='Get';List='Get';Query='Find';Create='New';CreateOrPoll='Invoke';Cancel='Stop';Void='Clear';Delete='Remove';Save='Set';Issue='Submit';Update='Set';Download='Receive';Search='Search';Manifest='Submit';Import='Import';Add='Add';Replace='Set';Close='Close';Correct='Edit';Confirm='Approve';Link='Join'}
$catalog=[Collections.Generic.List[object]]::new()
$source=[Text.StringBuilder]::new("# Generated by scripts/Generate.ps1 from the exact pinned public assembly.`n")
foreach($op in [Webmania.WebmaniaClient]::Operations){
    if($op.Id -notmatch '^(.*?)(CreateOrPoll|Get|List|Query|Create|Cancel|Void|Delete|Save|Issue|Update|Download|Search|Manifest|Import|Add|Replace|Close|Correct|Confirm|Link)(.+)$'){throw "Unmapped public operation $($op.Id)"}
    $prefix=$Matches[1];$action=$Matches[2];$noun=$Matches[3]
    if($action -eq 'Manifest'){$noun+='Manifestation'}
    if($action -eq 'Replace'){$noun+='Replacement'}
    if($action -eq 'Correct'){$noun+='Correction'}
    $name=$verbs[$action]+'-Webmania'+$prefix.Substring(0,1).ToUpperInvariant()+$prefix.Substring(1)+$noun
    $methodName=$op.Id.Substring(0,1).ToUpperInvariant()+$op.Id.Substring(1)+'Async'
    $method=[Webmania.WebmaniaClient].GetMethod($methodName)
    if($null -eq $method){throw "No exact facade $methodName"}
    $pt=TypeName $method.GetParameters()[0].ParameterType
    $rt=TypeName $method.ReturnType.GenericTypeArguments[0]
    [void]$source.Append(@"

function $name {
    <#
    .SYNOPSIS
    Executes pinned operation $($op.Id) using its public typed .NET facade.
    .DESCRIPTION
    Credential scope: $($op.Scope). Enabled: $($op.Enabled). No automatic retries or credential fallback.
    -Parameters is the exact $pt DTO. Optional fields default to omission; use Optional[T].Null for explicit null. Results retain exact numbers and typed unions.
    -AsTask returns the underlying task; keep Client alive until completion. Otherwise this command waits and emits the typed response envelope.
    #>
    [CmdletBinding()]
    [OutputType([$rt])]
    param(
        [Parameter(Mandatory)][ValidateNotNull()][Webmania.PowerShell.SafeType([Webmania.WebmaniaClient])][Webmania.WebmaniaClient]`$Client,
        [Parameter(Mandatory)][ValidateNotNull()][Webmania.PowerShell.SafeType([$pt])][$pt]`$Parameters,
        [Webmania.PowerShell.SafeType([Threading.CancellationToken])][Threading.CancellationToken]`$CancellationToken=[Threading.CancellationToken]::None,
        [Webmania.PowerShell.SafeType([Management.Automation.SwitchParameter])][switch]`$AsTask
    )
    try {
        Invoke-WebmaniaInternalCall -Client `$Client -MethodName '$methodName' -Parameters `$Parameters -CancellationToken `$CancellationToken -AsTask:`$AsTask
    } catch { Stop-WebmaniaError `$PSCmdlet `$_ }
}
"@)
    $catalog.Add([ordered]@{operationId=$op.Id;command=$name;method=$methodName;parametersType=$pt;outputType=$rt;scope=$op.Scope;enabled=$op.Enabled;contractStatus=($op.ContractStatus.GetRawText()|ConvertFrom-Json)})
}
if(@($catalog.command|Sort-Object -Unique).Count -ne $catalog.Count -or $catalog.Count -ne @([Webmania.WebmaniaClient]::Operations).Count){throw 'Command name collision'}
$source.ToString() | Set-Content (Join-Path $OutputDirectory 'Operations.ps1') -Encoding utf8NoBOM
$catalog|ConvertTo-Json -Depth 12|Set-Content (Join-Path $OutputDirectory 'commands.json') -Encoding utf8NoBOM
